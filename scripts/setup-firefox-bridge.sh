#!/usr/bin/env bash
#
# setup-firefox-bridge.sh: set up the bridge and the `ff` CLI. Idempotent.
#
#   npm run setup                  install deps, put `ff` on PATH
#   npm run setup -- --desktop     also register the MCP server with Claude Desktop
#   npm run setup -- --cowork      --desktop, plus LAN exposure with a token and a
#                                  firefox-bridge.plugin to upload to Cowork
#
# FIREFOX_BRIDGE_EXPOSE=1 is the same as --cowork. Re-run --cowork whenever your
# LAN IP changes, then re-upload the rebuilt plugin.
#
# Security: by default the HTTP endpoint binds 127.0.0.1 only. --cowork binds
# 0.0.0.0 and ALWAYS requires a generated token (stored in .firefox-bridge-token,
# gitignored); this script has no way to expose the endpoint without one.
#
# The default setup runs on macOS and Linux. --cowork is macOS only for now
# (LAN IP detection uses ipconfig/route).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SSE_PORT="${FIREFOX_BRIDGE_SSE_PORT:-3003}"
WS_PORT="${FIREFOX_BRIDGE_WS_PORT:-3002}"
PLUGIN_OUT="$REPO_ROOT/firefox-bridge.plugin"
BRIDGE_DIR="$REPO_ROOT/firefox-mcp-bridge"
EXT_MANIFEST="$REPO_ROOT/firefox-extension/manifest.json"
SECURE_CONFIG="$REPO_ROOT/scripts/secure-config.mjs"

DESKTOP_ON=0
EXPOSE_ON=0
case "${FIREFOX_BRIDGE_EXPOSE:-0}" in 1 | true | yes | on) EXPOSE_ON=1 ;; esac
for arg in "$@"; do
  case "$arg" in
    --desktop) DESKTOP_ON=1 ;;
    --cowork) EXPOSE_ON=1 ;;
    -h | --help) sed -n '3,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $arg (try --help)" >&2; exit 2 ;;
  esac
done
# Cowork reaches a bridge that Claude Desktop spawns with the LAN env.
[ "$EXPOSE_ON" = "1" ] && DESKTOP_ON=1

c_blue=$'\033[1;34m'; c_green=$'\033[1;32m'; c_yellow=$'\033[1;33m'; c_reset=$'\033[0m'
log()  { printf '%s▶ %s%s\n' "$c_blue"   "$*" "$c_reset"; }
ok()   { printf '%s✓ %s%s\n' "$c_green"  "$*" "$c_reset"; }
warn() { printf '%s⚠ %s%s\n' "$c_yellow" "$*" "$c_reset"; }

# 1. deps -------------------------------------------------------------------
if ! command -v npm >/dev/null 2>&1; then
  warn "npm not found on PATH — install Node.js, then re-run."; exit 1
fi
log "Installing bridge dependencies…"
npm install --prefix "$BRIDGE_DIR" --silent
ok "Dependencies ready."

# 1b. put `ff` on PATH ---------------------------------------------------
log "Linking the ff CLI onto your PATH…"
if (cd "$BRIDGE_DIR" && npm link >/dev/null 2>&1); then
  ok "ff CLI linked ($(command -v ff || echo 'open a new shell to pick it up'))"
else
  warn "npm link failed — you can still run it as: node $BRIDGE_DIR/cli.mjs"
fi

if [ "$DESKTOP_ON" = "1" ]; then

# 2. detect LAN IP ----------------------------------------------------------
detect_ip() {
  local ip=""
  for iface in en0 en1; do
    ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
    [ -n "$ip" ] && { printf '%s' "$ip"; return 0; }
  done
  local def
  def="$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')"
  [ -n "$def" ] && ipconfig getifaddr "$def" 2>/dev/null || true
}

# 3. decide bind host + token (by mode) -------------------------------------
TOKEN=""
if [ "$EXPOSE_ON" = "1" ]; then
  LAN_IP="${FIREFOX_BRIDGE_HOST_IP:-$(detect_ip)}"
  if [ -z "$LAN_IP" ]; then
    warn "Could not detect a LAN IP. Re-run as: FIREFOX_BRIDGE_HOST_IP=x.x.x.x FIREFOX_BRIDGE_EXPOSE=1 $0"; exit 1
  fi
  SSE_BIND_HOST="0.0.0.0"
  SSE_URL="http://$LAN_IP:$SSE_PORT/mcp"
  TOKEN="$(node "$SECURE_CONFIG" token)"   # ensures + prints (stored gitignored)
  ok "Expose mode: SSE will bind $SSE_BIND_HOST and require a token."
  ok "Token stored in .firefox-bridge-token  →  SSE url: $SSE_URL"
else
  SSE_BIND_HOST="127.0.0.1"
  SSE_URL="http://127.0.0.1:$SSE_PORT/mcp"
  ok "Localhost-only: HTTP endpoint binds 127.0.0.1."
fi

# 4. register bridge with Claude Desktop ------------------------------------
log "Registering bridge in Claude Desktop config…"
if [ "$EXPOSE_ON" = "1" ]; then
  FIREFOX_BRIDGE_SSE_HOST="$SSE_BIND_HOST" FIREFOX_BRIDGE_SSE_TOKEN="$TOKEN" \
    node "$REPO_ROOT/scripts/install-firefox-mcp-bridge.mjs"
else
  node "$REPO_ROOT/scripts/install-firefox-mcp-bridge.mjs"
fi

if [ "$EXPOSE_ON" = "1" ]; then
# 5. (re)build the Cowork plugin bundle -------------------------------------
log "Building $PLUGIN_OUT …"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/.claude-plugin"
cat > "$STAGE/.claude-plugin/plugin.json" <<'JSON'
{
  "name": "firefox-bridge",
  "version": "0.1.0",
  "description": "Control Firefox via a local MCP bridge"
}
JSON
# The plugin .mcp.json (with the bearer header in expose mode) is generated by
# the tested secure-config CLI; the header is included iff a token is set.
FIREFOX_BRIDGE_SSE_TOKEN="$TOKEN" node "$SECURE_CONFIG" plugin "$SSE_URL" > "$STAGE/.mcp.json"
rm -f "$PLUGIN_OUT"
( cd "$STAGE" && zip -q -X -r "$PLUGIN_OUT" .mcp.json .claude-plugin )
ok "Built $PLUGIN_OUT  (firefox-bridge → $SSE_URL)"
fi

# 6. health check -----------------------------------------------------------
log "Checking bridge ports…"
port_up() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
port_up "$WS_PORT"  && ok "WS relay listening on :$WS_PORT"     || warn "Nothing on :$WS_PORT — restart Claude Desktop to spawn the bridge."
port_up "$SSE_PORT" && ok "SSE endpoint listening on :$SSE_PORT" || warn "Nothing on :$SSE_PORT — restart Claude Desktop to spawn the bridge."

fi

# 7. remaining manual steps -------------------------------------------------
cat <<EOF

${c_blue}────────────────────────────────────────────────────────────${c_reset}
 Install the extension: open the signed .xpi in Firefox from
   https://github.com/Jetemple/firefox-agent-bridge/releases/latest
 Or run it from this checkout: about:debugging#/runtime/this-firefox
   → "Load Temporary Add-on…" → $EXT_MANIFEST

 Try it:  ff status   ·   ff tabs   ·   ff nav example.com   ·   ff --help
EOF
if [ "$DESKTOP_ON" = "1" ]; then
  echo " Restart Claude Desktop so it respawns the bridge with the new settings."
fi
if [ "$EXPOSE_ON" = "1" ]; then
  cat <<EOF
 Cowork → Settings → Upload local plugin → $PLUGIN_OUT
 ${c_yellow}Exposed on the LAN with a token.${c_reset} Keep .firefox-bridge-token secret.
 New network or IP?  Re-run with --cowork and re-upload the plugin.
EOF
fi
printf '%s────────────────────────────────────────────────────────────%s\n' "$c_blue" "$c_reset"
